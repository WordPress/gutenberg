const blockDirs = getBlockDirs();

// Group blocks by category.
const categories = {};
blockDirs.forEach( ( blockDir ) => {
	const blockJson = readBlockJson( blockDir );
	const category = blockJson.category || 'uncategorized';
	if ( ! categories[ category ] ) {
		categories[ category ] = [];
	}
	categories[ category ].push( blockDir );
} );

// Ensure category output directory exists.
fs.mkdirSync( CATEGORY_DOCS_DIR, { recursive: true } );

// Generate individual block READMEs in their source directories.
