/**
 * Generate the token-delimited API reference content for a block.
 *
 * @param {string} blockDir Directory name.
 * @return {string} Markdown content wrapped in START/END TOKEN delimiters.
 */
function generateBlockApiSection( blockDir ) {
	const blockJson = readBlockJson( blockDir );
	const files = getBlockFiles( blockDir );
	const blockType = getBlockType( files );

	const {
		name,
		title,
		category,
		description,
		keywords,
		apiVersion,
		attributes,
		supports,
		usesContext,
		providesContext,
		styles,
		selectors,
	} = blockJson;

	const slug = name.replace( 'core/', '' );
	const lines = [];

	// Metadata.
	lines.push( `**Name:** \`${ name }\`` );
	const catSlug = `core-blocks-${ category }`;
	lines.push(
		`**Category:** [${ category }](/block-editor/reference-guides/core-blocks/${ catSlug }/)`
	);
	if ( apiVersion ) {
		lines.push(
			`**API Version:** [${ apiVersion }](/block-editor/reference-guides/block-api/block-api-versions/)`
		);
	}

	const RENDERING_GUIDE =
		'/block-editor/getting-started/fundamentals/static-dynamic-rendering/';
	const typeLabel = {
		static: `[Static](${ RENDERING_GUIDE }) (saved in post content)`,
		dynamic: `[Dynamic](${ RENDERING_GUIDE }) (server-rendered)`,
		hybrid: `[Hybrid](${ RENDERING_GUIDE }) (static save + server enhancements)`,
	};
	lines.push( `**Block Type:** ${ typeLabel[ blockType ] || 'Unknown' }` );
	lines.push( '' );

	if ( description ) {
		lines.push( `> ${ description }` );
		lines.push( '' );
	}

	if ( keywords && keywords.length > 0 ) {
		lines.push(
			`**Keywords:** ${ keywords
				.map( ( k ) => `\`${ k }\`` )
				.join( ', ' ) }`
		);
		lines.push( '' );
	}

	// Block relationships.
	const relationships = formatRelationships( blockJson );
	if ( relationships ) {
		lines.push( '## Block Relationships' );
		lines.push( '' );
		lines.push( relationships );
		lines.push( '' );
	}

	// Attributes.
	lines.push( '## Attributes' );
	lines.push( '' );
	lines.push(
		'_Defined via the [`attributes`](/block-editor/reference-guides/block-api/block-attributes/) property in block.json._'
	);
	lines.push( '' );
	lines.push( formatAttributesTable( attributes ) );
	lines.push( '' );

	// Supports.
	lines.push( '## Supports' );
	lines.push( '' );
	lines.push(
		'_Defined via the [`supports`](/block-editor/reference-guides/block-api/block-supports/) property in block.json._'
	);
	lines.push( '' );
	lines.push( formatSupports( supports ) );
	lines.push( '' );

	// Context.
	const contextSection = formatContext( usesContext, providesContext );
	if ( contextSection ) {
		lines.push( '## Context' );
		lines.push( '' );
		lines.push(
			'_Defined via the [`usesContext` and `providesContext`](/block-editor/reference-guides/block-api/block-context/) properties in block.json._'
		);
		lines.push( '' );
		lines.push( contextSection );
		lines.push( '' );
	}

	// Styles.
	const stylesSection = formatStyles( styles );
	if ( stylesSection ) {
		lines.push( '## Block Styles' );
		lines.push( '' );
		lines.push(
			'_Defined via the [`styles`](/block-editor/reference-guides/block-api/block-styles/) property in block.json._'
		);
		lines.push( '' );
		lines.push( stylesSection );
		lines.push( '' );
	}

	// Selectors.
	const selectorsSection = formatSelectors( selectors );
	if ( selectorsSection ) {
		lines.push( '## CSS Selectors' );
		lines.push( '' );
		lines.push(
			'_Defined via the [`selectors`](/block-editor/reference-guides/block-api/block-selectors/) property in block.json._'
		);
		lines.push( '' );
		lines.push( selectorsSection );
		lines.push( '' );
	}

	// Block markup example.
	lines.push( '## Block Markup' );
	lines.push( '' );
	if ( blockType === 'dynamic' ) {
		lines.push(
			'This is a [**dynamic block**](/block-editor/getting-started/fundamentals/static-dynamic-rendering/). It is rendered on the server and does not save HTML in post content.'
		);
		lines.push( '' );
		lines.push( 'In post content, it is stored as a block comment:' );
	} else if ( blockType === 'hybrid' ) {
		lines.push(
			'This is a [**hybrid block**](/block-editor/getting-started/fundamentals/static-dynamic-rendering/). It saves static markup that the server may enhance during rendering.'
		);
	} else {
		lines.push(
			'This is a [**static block**](/block-editor/getting-started/fundamentals/static-dynamic-rendering/). The markup is saved directly in the post content.'
		);
	}
	lines.push( '' );
	lines.push( '```html' );
	lines.push(
		generateBlockCommentExample( slug, attributes, blockType )
	);
	lines.push( '```' );
	lines.push( '' );

	// Source files reference.
	lines.push( '## Source' );
	lines.push( '' );
	lines.push(
		`- [block.json](${ SOURCE_URL_BASE }${ blockDir }/block.json) ([reference](/block-editor/reference-guides/block-api/block-metadata/))`
	);
	if ( files.hasEditJs ) {
		lines.push(
			`- [edit.js](${ SOURCE_URL_BASE }${ blockDir }/edit.js)`
		);
	}
	if ( files.hasSaveJs ) {
		lines.push(
			`- [save.js](${ SOURCE_URL_BASE }${ blockDir }/save.js)`
		);
	}
	if ( files.hasIndexPhp ) {
		lines.push(
			`- [index.php](${ SOURCE_URL_BASE }${ blockDir }/index.php)`
		);
	}
	if ( files.hasDeprecated ) {
		lines.push(
			`- [deprecated.js](${ SOURCE_URL_BASE }${ blockDir }/deprecated.js)`
		);
	}
	if ( files.hasVariations ) {
		lines.push(
			`- [variations.js](${ SOURCE_URL_BASE }${ blockDir }/variations.js)`
		);
	}
	lines.push( '' );

	return `${ TOKEN_START }\n${ lines.join( '\n' ) }\n${ TOKEN_END }\n`;
}

/**
 * Write a block's README.md with token-delimited generated content.
 *
 * - File doesn't exist → create with H1 title + description + tokens.
 * - File exists, no tokens → append tokens at the end.
 * - File exists, has tokens → replace content between tokens.
 *
 * @param {string} blockDir   Directory name inside block-library/src.
 * @param {string} apiSection Token-wrapped generated content.
 */
function writeBlockReadme( blockDir, apiSection ) {
	const readmePath = path.join( BLOCK_LIBRARY_DIR, blockDir, 'README.md' );
	const blockJson = readBlockJson( blockDir );
	const { title, description } = blockJson;

	if ( ! fs.existsSync( readmePath ) ) {
		// Case 1: No README — create full file.
		const header = `# ${ title }\n\n`;
		fs.writeFileSync( readmePath, header + apiSection, {
			encoding: 'utf8',
		} );
		return;
	}

	const existing = fs.readFileSync( readmePath, 'utf8' );

	if ( existing.includes( TOKEN_START ) ) {
		// Case 3: Tokens exist — replace content between them.
		const tokenPattern = new RegExp(
			escapeRegExp( TOKEN_START ) +
				'[\\s\\S]*?' +
				escapeRegExp( TOKEN_END ) +
				'\\n?',
			'm'
		);
		fs.writeFileSync(
			readmePath,
			existing.replace( tokenPattern, apiSection ),
			{ encoding: 'utf8' }
		);
		return;
	}

	// Case 2: File exists but no tokens — append at the end.
	const separator = existing.endsWith( '\n' ) ? '\n' : '\n\n';
	fs.writeFileSync( readmePath, existing + separator + apiSection, {
		encoding: 'utf8',
	} );
}

/**
 * Escape a string for use in a RegExp.
 *
 * @param {string} str
 * @return {string}
 */
function escapeRegExp( str ) {
	return str.replace( /[.*+?^${}()|[\]\\]/g, '\\$&' );
}

/**
 * Generate a category index page that links to individual block pages.
 *
 * @param {string}   category Category slug.
 * @param {string}   label    Human-readable category name.
 * @param {string[]} blocks   Block directory names in this category.
 * @return {string} Markdown document.
 */
function generateCategoryPage( category, label, blocks ) {
	const lines = [];

	lines.push( `# ${ label } Blocks` );
	lines.push( '' );

	blocks.forEach( ( blockDir ) => {
		const blockJson = readBlockJson( blockDir );
		const { title, name, description } = blockJson;
		const catSlug = `core-blocks-${ category }`;
		const blockSlug = `core-block-${ blockDir }`;
		const blockUrl = `/block-editor/reference-guides/core-blocks/${ catSlug }/${ blockSlug }/`;
		lines.push(
			`- [${ title }](${ blockUrl }) — \`${ name }\`${
				description ? ': ' + description : ''
			}`
		);
	} );

	lines.push( '' );

	return lines.join( '\n' );
}

