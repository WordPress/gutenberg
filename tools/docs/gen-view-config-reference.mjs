/**
 * Generates the view config reference documentation from the view config REST
 * schema — the single source of truth, also consumed by the REST controller.
 *
 * Reads from  : lib/compat/wordpress-7.1/view-config-schema.php
 *               (extracted via tools/docs/dump-view-config-schema.php)
 * Publishes to: docs/reference-guides/view-config-reference.md
 */

/**
 * External dependencies
 */
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import execa from 'execa';

/**
 * Path to the PHP script that dumps the view config schema as JSON.
 *
 * @type {string}
 */
const DUMP_SCRIPT_PATH = fileURLToPath(
	new URL( './dump-view-config-schema.php', import.meta.url )
);

/**
 * Path to docs file.
 *
 * @type {string}
 */
const REFERENCE_DOC_PATH = fileURLToPath(
	new URL(
		'../../docs/reference-guides/view-config-reference.md',
		import.meta.url
	)
);

/**
 * Builds the start token delimiting a generated section in the doc file.
 *
 * @param {string} section Top-level schema key the section documents.
 * @return {string} Start token.
 */
const startToken = ( section ) =>
	`<!-- START TOKEN Autogenerated - DO NOT EDIT (${ section }) -->`;

/**
 * Builds the end token delimiting a generated section in the doc file.
 *
 * @param {string} section Top-level schema key the section documents.
 * @return {string} End token.
 */
const endToken = ( section ) =>
	`<!-- END TOKEN Autogenerated - DO NOT EDIT (${ section }) -->`;

/**
 * Maximum number of keys included in a `{ key, … }` object summary before
 * falling back to a plain `object` label.
 *
 * @type {number}
 */
const OBJECT_SUMMARY_MAX_KEYS = 8;

/**
 * Maximum number of enum values rendered as a `a | b | c` union in the Type
 * column before falling back to the primitive type label.
 *
 * @type {number}
 */
const ENUM_SUMMARY_MAX_VALUES = 6;

/**
 * Serializes a schema node into a compact human-readable type label.
 *
 * Objects render as `{ key1, key2 }` summaries, maps (via
 * `additionalProperties`) as `{ [ key ]: … }`, arrays as `[ itemType ]`, and
 * small unions (`oneOf`/`anyOf`) join their branches with `|`. A union of
 * three or more object branches discriminated by a single-value `type` enum
 * renders as `{ type: a | b | c, … }`.
 *
 * @param {Object} schema Schema node.
 * @return {string} Serialized type, without backticks or escaping.
 */
function formatType( schema ) {
	if ( ! schema || typeof schema !== 'object' ) {
		return 'any';
	}

	const branches = schema.oneOf || schema.anyOf;
	if ( branches ) {
		const isDiscriminatedObjectUnion =
			branches.length >= 3 &&
			branches.every(
				( branch ) =>
					branch.type === 'object' &&
					branch.properties?.type?.enum?.length === 1
			);
		if ( isDiscriminatedObjectUnion ) {
			const variants = branches.map(
				( branch ) => branch.properties.type.enum[ 0 ]
			);
			return `{ type: ${ variants.join( ' | ' ) }, … }`;
		}
		const formatted = branches.map( formatType ).filter( Boolean );
		return [ ...new Set( formatted ) ].join( ' | ' );
	}

	if ( Array.isArray( schema.type ) ) {
		return schema.type.join( ' | ' );
	}

	if ( schema.enum && schema.enum.length <= ENUM_SUMMARY_MAX_VALUES ) {
		return schema.enum.join( ' | ' );
	}

	if ( schema.type === 'object' ) {
		if ( schema.properties ) {
			const keys = Object.keys( schema.properties );
			if ( keys.length <= OBJECT_SUMMARY_MAX_KEYS ) {
				return `{ ${ keys.join( ', ' ) } }`;
			}
			return 'object';
		}
		if ( schema.additionalProperties?.type ) {
			return `{ [ fieldId ]: ${ formatType(
				schema.additionalProperties
			) } }`;
		}
		return 'object';
	}

	if ( schema.type === 'array' ) {
		if ( schema.items ) {
			return `[ ${ formatType( schema.items ) } ]`;
		}
		return 'array';
	}

	return schema.type || 'any';
}

/**
 * Wraps a serialized type in backticks and escapes pipes for use in a
 * markdown table cell.
 *
 * @param {Object} schema Schema node.
 * @return {string} Markdown table cell content.
 */
function formatTypeCell( schema ) {
	return `\`${ formatType( schema ) }\``.replace( /\|/g, '\\|' );
}

/**
 * Renders a markdown table for a map of property schemas. A Default column is
 * added only when at least one property declares a default.
 *
 * @param {Object} properties Map of property name to schema node.
 * @return {string} Markdown table.
 */
function renderTable( properties ) {
	const entries = Object.entries( properties );
	const hasDefaults = entries.some( ( [ , schema ] ) => 'default' in schema );

	let md = hasDefaults
		? '| Property | Description | Type | Default |\n| -------- | ----------- | ---- | ------- |\n'
		: '| Property | Description | Type |\n| -------- | ----------- | ---- |\n';

	for ( const [ property, schema ] of entries ) {
		// Assuming that the first line of a description is a summary.
		const description = schema.description?.split( '\n', 1 )[ 0 ] ?? '';
		const cells = [ property, description, formatTypeCell( schema ) ];
		if ( hasDefaults ) {
			cells.push(
				'default' in schema
					? `\`${ JSON.stringify( schema.default ) }\``
					: ''
			);
		}
		md += `| ${ cells.join( ' | ' ) } |\n`;
	}

	return md;
}

/**
 * Renders the `default_view` section: a single table of view properties.
 *
 * @param {Object} schema The item schema.
 * @return {string} Markdown content.
 */
function renderDefaultView( schema ) {
	return renderTable( schema.properties.default_view.properties );
}

/**
 * Renders the `default_layouts` section: a summary table of the layout types,
 * followed by one subsection per type listing its layout-specific options.
 *
 * @param {Object} schema The item schema.
 * @return {string} Markdown content.
 */
function renderDefaultLayouts( schema ) {
	const layoutTypes = schema.properties.default_layouts.properties;

	let md = renderTable( layoutTypes );
	md += '\n';
	md +=
		'Each layout type accepts all the [view properties](#default_view) as overrides (except `type`), plus a `layout` object with options specific to that layout type:\n';

	for ( const [ layoutType, layoutTypeSchema ] of Object.entries(
		layoutTypes
	) ) {
		const layout = layoutTypeSchema.properties.layout;
		md += `\n### ${ layoutType }\n\n`;
		if ( layout.description ) {
			md += `${ layout.description }\n\n`;
		}
		md += renderTable( layout.properties );
	}

	return md;
}

/**
 * Renders the `view_list` section: a table of the properties of each entry.
 *
 * @param {Object} schema The item schema.
 * @return {string} Markdown content.
 */
function renderViewList( schema ) {
	return renderTable( schema.properties.view_list.items.properties );
}

/**
 * Renders the `form` section: the top-level form table, the form field object
 * table, and one subsection per form layout variant.
 *
 * @param {Object} schema The item schema.
 * @return {string} Markdown content.
 */
function renderForm( schema ) {
	const form = schema.properties.form;

	let md = renderTable( form.properties );

	// Form field objects.
	const fieldObjectBranch = form.properties.fields.items.oneOf.find(
		( branch ) => branch.type === 'object'
	);
	md += '\n### Form fields\n\n';
	md += 'A field declared as an object accepts:\n\n';
	md += renderTable( fieldObjectBranch.properties );

	// Form layout variants.
	md += '\n### Form layout variants\n\n';
	md +=
		'A form layout — the form `layout` or a field `layout` — is one of the following variants, discriminated by its `type` property:\n';
	for ( const branch of form.properties.layout.oneOf ) {
		const variant = branch.properties.type.enum[ 0 ];
		md += `\n#### ${ variant }\n\n`;
		if ( branch.description ) {
			md += `${ branch.description }\n\n`;
		}
		md += renderTable( branch.properties );
	}

	return md;
}

/**
 * Splices generated content into the doc between the section's tokens.
 *
 * @param {string} doc     Current doc contents.
 * @param {string} section Top-level schema key of the section.
 * @param {string} content Generated markdown for the section.
 * @return {string} Updated doc contents.
 */
function spliceSection( doc, section, content ) {
	const start = startToken( section );
	const end = endToken( section );
	const startIndex = doc.indexOf( start );
	const endIndex = doc.indexOf( end );

	if ( startIndex === -1 || endIndex === -1 || endIndex < startIndex ) {
		throw new Error(
			`Could not find the "${ start }" / "${ end }" token pair in ${ REFERENCE_DOC_PATH }.`
		);
	}

	return (
		doc.slice( 0, startIndex + start.length ) +
		'\n\n' +
		content +
		'\n' +
		doc.slice( endIndex )
	);
}

/**
 * Main function.
 */
async function main() {
	let stdout;
	try {
		( { stdout } = await execa( 'php', [ DUMP_SCRIPT_PATH ] ) );
	} catch ( error ) {
		if ( error.code === 'ENOENT' ) {
			throw new Error(
				'PHP is required to generate the view config reference: the schema is extracted from its PHP source file via `php`. Install PHP and make sure it is available on your PATH.'
			);
		}
		throw error;
	}

	const schema = JSON.parse( stdout );

	const sections = {
		default_view: renderDefaultView,
		default_layouts: renderDefaultLayouts,
		view_list: renderViewList,
		form: renderForm,
	};

	let doc = await fs.readFile( REFERENCE_DOC_PATH, { encoding: 'utf8' } );

	for ( const [ section, render ] of Object.entries( sections ) ) {
		doc = spliceSection( doc, section, render( schema ) );
	}

	await fs.writeFile( REFERENCE_DOC_PATH, doc, { encoding: 'utf8' } );
}

main().catch( ( error ) => {
	console.error( error );
	process.exit( 1 );
} );
