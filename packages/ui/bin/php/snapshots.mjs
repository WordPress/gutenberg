/**
 * Turning rendered HTML into snapshots PHP fills in, and into the reviewable
 * `snapshot.html` files.
 */
export const SLOT_PATTERN = /__wpuislot_([a-z0-9_]+)__/;

/**
 * Removes attributes that only Base UI's JavaScript reads, such as
 * `data-base-ui-tooltip-trigger`, unless a stylesheet uses them.
 *
 * @param {string} html Rendered HTML.
 * @param {string} css  Every compiled stylesheet.
 * @return {string} HTML.
 */
export function stripRuntimeAttributes( html, css ) {
	return html.replace(
		/ (data-base-ui-[a-z-]+)(="[^"]*")?/g,
		( match, name ) => ( css.includes( name ) ? match : '' )
	);
}

/**
 * Splits rendered HTML into a snapshot: literal HTML, and the parts PHP fills
 * in at render time.
 *
 *   - `[ 'slot', prop, 'text' ]`             A slot prop in text, escaped as HTML.
 *   - `[ 'slot', prop, 'attribute', name ]`  A slot prop in an attribute, escaped for it.
 *
 * @param {string} html Rendered HTML.
 * @return {Array} Snapshot parts.
 */
export function toSnapshot( html ) {
	const pattern = new RegExp( SLOT_PATTERN.source, 'g' );
	const parts = [];
	let offset = 0;

	for ( const match of html.matchAll( pattern ) ) {
		if ( match.index > offset ) {
			parts.push( html.slice( offset, match.index ) );
		}
		offset = match.index + match[ 0 ].length;

		const before = html.slice( 0, match.index );
		const inTag = before.lastIndexOf( '<' ) > before.lastIndexOf( '>' );

		// In an attribute, record which one, so PHP can escape URLs as URLs.
		const attribute = inTag
			? before.match( /([^\s=<]+)="[^"]*$/ )?.[ 1 ]
			: null;
		parts.push(
			attribute
				? [ 'slot', match[ 1 ], 'attribute', attribute ]
				: [ 'slot', match[ 1 ], 'text' ]
		);
	}
	if ( offset < html.length ) {
		parts.push( html.slice( offset ) );
	}

	return parts;
}

/**
 * Formats a component's example renders as the reviewable snapshot file.
 *
 * Scoped class names are written as the class they come from, such as
 * `button/style:is-brand`, so the file only changes when the markup does, and
 * not when class name hashes change.
 *
 * @param {Array}               examples   The component's examples.
 * @param {Map<string, string>} classNames Class reference per scoped class name.
 * @return {string} File contents.
 */
export function formatSnapshotFile( examples, classNames ) {
	const readable = ( html ) =>
		html.replace(
			/ class="([^"]*)"/g,
			( match, value ) =>
				` class="${ value
					.split( ' ' )
					.map( ( name ) => classNames.get( name ) ?? name )
					.join( ' ' ) }"`
		);
	return (
		'<!-- Generated by packages/ui/bin/build-php.mjs from the React components. Update with `npm run update-php-snapshots --workspace @wordpress/ui`. -->\n' +
		examples
			.map(
				( { name, html } ) =>
					`\n<!-- ${ name } -->\n${ readable( html ) }\n`
			)
			.join( '' )
	);
}
