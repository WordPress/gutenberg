/**
 * Return the exact theme ramps generated by trunk for the fixed Storybook
 * samples. Trunk had four foreground steps, so fgSurface5 mirrors fgSurface4
 * only to keep the comparison data shape compatible with the current branch.
 */
export function getTrunkProductionThemeRamps(
	background: string,
	primary: string
): TrunkProductionThemeRamps {
	const key = `${ background.toLowerCase() }|${ primary.toLowerCase() }`;
	const ramps = TRUNK_PRODUCTION_FIXTURES[ key ];

	if ( ! ramps ) {
		throw new Error( `No trunk production fixture exists for ${ key }.` );
	}

	return ramps;
}
