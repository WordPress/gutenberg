import { FORMAT_ID } from '@terrazzo/plugin-css';
import type { Plugin } from '@terrazzo/parser';
import {
	createTokenFallbackResolver,
	formatDesignTokenFallbacksScss,
} from './fallbacks.ts';

interface TokenMetadata {
	$description: string;
	$type: string;
	group: string;
	fallback: string;
	modes: {
		default: {
			$value: unknown;
			css: string;
		};
	};
}

interface PluginTokenDataOptions {
	filename?: string;
	fallbacksFilename?: string;
	scssFilename?: string | false;
	additionalScssFilenames?: string[];
}

export default function pluginTokenData( {
	filename = 'js/design-tokens.mjs',
	fallbacksFilename = 'js/design-token-fallbacks.mjs',
	scssFilename = 'scss/design-token-fallbacks.scss',
	additionalScssFilenames = [],
}: PluginTokenDataOptions = {} ): Plugin {
	return {
		name: '@wordpress/terrazzo-plugin-token-data',
		async build( { getTransforms, outputFile } ) {
			const tokens: Record< string, TokenMetadata > = {};
			const groups: Record< string, string[] > = {};
			const getFallback = createTokenFallbackResolver();

			// '.' is Terrazzo's identifier for the default (base) mode.
			for ( const token of getTransforms( {
				format: FORMAT_ID,
				id: '*',
				mode: '.',
			} ) ) {
				if ( ! token.localID ) {
					console.warn(
						'Unexpected — Missing local ID when building token metadata'
					);
					continue;
				}

				// Resolver tokens share the resolver's source location, so group by
				// the stable token namespace. This matches the documentation plugin.
				const group =
					token.token.id.split( '.' )[ 0 ]?.replace( /^wpds-/, '' ) ||
					'unknown';

				const css = typeof token.value === 'string' ? token.value : '';

				tokens[ token.localID ] = {
					$description: token.token.$description ?? '',
					$type: token.token.$type,
					group,
					fallback: getFallback( token.localID, css ),
					modes: {
						default: {
							$value: token.token.$value,
							css,
						},
					},
				};

				groups[ group ] ??= [];
				groups[ group ].push( token.localID );
			}

			outputFile(
				filename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-token-data plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					`export const tokens = /** @type {const} */ ( ${ JSON.stringify(
						tokens,
						null,
						'\t'
					) } );`,
					'',
					`export const groups = ${ JSON.stringify(
						groups,
						null,
						'\t'
					) };`,
					'',
					'export default Object.keys( tokens );',
					'',
				].join( '\n' )
			);

			const sorted = Object.fromEntries(
				Object.entries( tokens )
					.sort( ( [ a ], [ b ] ) => a.localeCompare( b ) )
					.map( ( [ name, token ] ) => [ name, token.fallback ] )
			);

			const generatedHeader = [
				'/*',
				' * This file is generated by the @wordpress/terrazzo-plugin-token-data plugin.',
				' * Do not edit this file directly.',
				' */',
				'',
			].join( '\n' );

			outputFile(
				fallbacksFilename,
				generatedHeader +
					`export default ${ JSON.stringify( sorted, null, '\t' ) }` +
					'\n'
			);

			const scssFilenames = [
				...( scssFilename ? [ scssFilename ] : [] ),
				...additionalScssFilenames,
			];

			const scss = formatDesignTokenFallbacksScss( sorted );
			for ( const currentScssFilename of scssFilenames ) {
				outputFile( currentScssFilename, scss );
			}
		},
	};
}
