/**
 * External dependencies
 */
import { FORMAT_ID } from '@terrazzo/plugin-css';
import type { Plugin } from '@terrazzo/parser';

export default function pluginKnownWpdsCssVariables( {
	filename = 'design-tokens.mjs',
} = {} ): Plugin {
	return {
		name: '@wordpress/terrazzo-plugin-known-wpds-css-variables',
		async build( { getTransforms, outputFile } ) {
			// Either a string (modes=false) or an object (modes=true)
			const tokensToExport: Record<
				string,
				Record< string, string | Record< string, string > >
			> = {};

			for ( const token of getTransforms( {
				format: FORMAT_ID,
				id: '*',
			} ) ) {
				if ( ! token.localID ) {
					console.warn(
						'Unexpected — Missing local ID when building token list for eslint plugin'
					);
					continue;
				}

				// Composite tokens (e.g. typography) expand into multiple CSS variables
				if ( typeof token.value === 'object' && token.value !== null ) {
					for ( const prop of Object.keys( token.value ) ) {
						const expandedId = `${ token.localID }-${ prop }`;
						tokensToExport[ expandedId ] ??= {};
						tokensToExport[ expandedId ][ token.mode ] =
							token.value[ prop ];
					}
				} else {
					tokensToExport[ token.localID ] ??= {};
					tokensToExport[ token.localID ][ token.mode ] = token.value;
				}
			}

			outputFile(
				filename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-known-wpds-css-variables plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					`export default ${ JSON.stringify(
						Array.from( new Set( Object.keys( tokensToExport ) ) ),
						null,
						2
					) }`,
					'', // final empty line
				].join( '\n' )
			);
		},
	};
}
