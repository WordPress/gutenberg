/**
 * External dependencies
 */
import { FORMAT_ID } from '@terrazzo/plugin-css';
import type { Plugin } from '@terrazzo/parser';

interface TokenMetadata {
	$description: string;
	$type: string;
	group: string;
	modes?: {
		default: {
			$value: unknown;
			css: string;
		};
	};
}

export default function pluginKnownWpdsCssVariables( {
	filename = 'design-tokens.mjs',
} = {} ): Plugin {
	return {
		name: '@wordpress/terrazzo-plugin-known-wpds-css-variables',
		async build( { getTransforms, outputFile } ) {
			const tokens: Record< string, TokenMetadata > = {};
			const groups: Record< string, string[] > = {};

			// '.' is Terrazzo's identifier for the default (base) mode.
			for ( const token of getTransforms( {
				format: FORMAT_ID,
				id: '*',
				mode: '.',
			} ) ) {
				if ( ! token.localID ) {
					console.warn(
						'Unexpected — Missing local ID when building token list'
					);
					continue;
				}

				const group =
					token.token.source.loc
						?.split( '/' )
						.at( -1 )
						?.split( '.json' )[ 0 ] ?? 'unknown';

				const isBrandToken = token.localID.includes( 'brand' );

				const tokenEntry: TokenMetadata = {
					$description: token.token.$description ?? '',
					$type: token.token.$type,
					group,
				};

				if ( ! isBrandToken ) {
					tokenEntry.modes = {
						default: {
							$value: token.token.$value,
							css: token.value,
						},
					};
				}

				tokens[ token.localID ] = tokenEntry;

				groups[ group ] ??= [];
				groups[ group ].push( token.localID );
			}

			outputFile(
				filename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-known-wpds-css-variables plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					`export const tokens = ${ JSON.stringify(
						tokens,
						null,
						'\t'
					) };`,
					'',
					`export const groups = ${ JSON.stringify(
						groups,
						null,
						'\t'
					) };`,
					'',
				].join( '\n' )
			);
		},
	};
}
