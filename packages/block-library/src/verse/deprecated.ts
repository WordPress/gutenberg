import metadata from './block.json';
import migrateFontFamily from '../utils/migrate-font-family';
import migrateTextAlign from '../utils/migrate-text-align';

const { attributes: blockAttributes, supports: blockSupports } = metadata;

type VerseAttributes = Record< string, unknown > & {
	textAlign?: string;
	className?: string;
	style?: { typography?: { fontFamily?: string } };
};

/**
 * Deprecation for the `textAlign` attribute, moved to the typography block
 * support, and for the font family preset stored in `style`, moved to the
 * `fontFamily` attribute.
 *
 * Attribute-only: the markup of those versions (an inline `text-align`
 * style or a `has-text-align-*` class, the font family class) is
 * regenerated by the parser from the migrated attributes.
 */
const legacyTextAlignAndFontFamily = {
	attributes: {
		...blockAttributes,
		textAlign: {
			type: 'string',
		},
	},
	supports: blockSupports,
	isEligible( { style, textAlign, className }: VerseAttributes ) {
		return (
			!! style?.typography?.fontFamily ||
			!! textAlign ||
			!! className?.match( /\bhas-text-align-(left|center|right)\b/ )
		);
	},
	migrate( attributes: VerseAttributes ) {
		return migrateTextAlign( migrateFontFamily( attributes ) );
	},
};

export default [ legacyTextAlignAndFontFamily ];
