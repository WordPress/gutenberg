import clsx from 'clsx';
import { compose } from '@wordpress/compose';
import metadata from './block.json';
import migrateFontFamily from '../utils/migrate-font-family';
import migrateTextAlign from '../utils/migrate-text-align';

const { attributes: blockAttributes, supports: blockSupports } = metadata;

type Style = Record< string, unknown > & {
	border?: Record< string, unknown > & { radius?: unknown };
	color?: Record< string, unknown >;
	dimensions?: Record< string, unknown >;
	typography?: Record< string, unknown > & { fontFamily?: string };
};

type ButtonAttributes = Record< string, unknown > & {
	align?: string;
	borderRadius?: number;
	className?: string;
	color?: string;
	customBackgroundColor?: string;
	customGradient?: string;
	customTextColor?: string;
	style?: Style;
	textAlign?: string;
	textColor?: string;
	width?: number | string;
};

const migrateWidth = ( attributes: ButtonAttributes ): ButtonAttributes => {
	const { width, ...otherAttributes } = attributes;

	if ( ! width ) {
		return otherAttributes;
	}

	return {
		...otherAttributes,
		style: {
			...otherAttributes.style,
			dimensions: {
				...otherAttributes.style?.dimensions,
				width: `${ width }%`,
			},
		},
	};
};

const migrateBorderRadius = (
	attributes: ButtonAttributes
): ButtonAttributes => {
	const { borderRadius, ...newAttributes } = attributes;
	// We have to check old property `borderRadius` and if
	// `styles.border.radius` is a `number`
	const oldBorderRadius = [
		borderRadius,
		newAttributes.style?.border?.radius,
	].find( ( possibleBorderRadius ) => {
		return (
			typeof possibleBorderRadius === 'number' &&
			possibleBorderRadius !== 0
		);
	} );
	if ( ! oldBorderRadius ) {
		return newAttributes;
	}

	return {
		...newAttributes,
		style: {
			...newAttributes.style,
			border: {
				...newAttributes.style?.border,
				radius: `${ oldBorderRadius }px`,
			},
		},
	};
};

const LEGACY_ALIGNMENTS = [ 'left', 'center', 'right' ];

function migrateAlign( attributes: ButtonAttributes ): ButtonAttributes {
	if (
		! attributes.align ||
		! LEGACY_ALIGNMENTS.includes( attributes.align )
	) {
		return attributes;
	}
	const { align, ...otherAttributes } = attributes;
	return {
		...otherAttributes,
		className: clsx( otherAttributes.className, `align${ align }` ),
	};
}

const migrateCustomColorsAndGradients = (
	attributes: ButtonAttributes
): ButtonAttributes => {
	if (
		! attributes.customTextColor &&
		! attributes.customBackgroundColor &&
		! attributes.customGradient
	) {
		return attributes;
	}
	const style: Style = { color: {} };
	if ( attributes.customTextColor ) {
		style.color!.text = attributes.customTextColor;
	}
	if ( attributes.customBackgroundColor ) {
		style.color!.background = attributes.customBackgroundColor;
	}
	if ( attributes.customGradient ) {
		style.color!.gradient = attributes.customGradient;
	}
	const {
		customTextColor,
		customBackgroundColor,
		customGradient,
		...restAttributes
	} = attributes;
	return {
		...restAttributes,
		style,
	};
};

// The oldest versions stored hex values in `color` and `textColor`.
const isHex = ( value: unknown ): value is string =>
	typeof value === 'string' && '#' === value[ 0 ];

const migrateOldColors = ( attributes: ButtonAttributes ): ButtonAttributes => {
	if ( attributes.color === undefined && ! isHex( attributes.textColor ) ) {
		return attributes;
	}
	const { color, textColor, ...restAttributes } = {
		...attributes,
		customTextColor: isHex( attributes.textColor )
			? attributes.textColor
			: undefined,
		customBackgroundColor: isHex( attributes.color )
			? attributes.color
			: undefined,
	};
	return migrateCustomColorsAndGradients( restAttributes );
};

// The squared block style became the absence of a border radius.
const migrateSquaredStyle = (
	attributes: ButtonAttributes
): ButtonAttributes => {
	if ( ! attributes.className?.includes( 'is-style-squared' ) ) {
		return attributes;
	}
	const newClassName = attributes.className
		.replace( /is-style-squared[\s]?/, '' )
		.trim();
	return migrateBorderRadius(
		migrateCustomColorsAndGradients( {
			...attributes,
			className: newClassName ? newClassName : undefined,
			borderRadius: 0,
		} )
	);
};

/**
 * Deprecation for every legacy attribute shape of the button: a numeric
 * `width` (percentage) and `borderRadius` (pixels), `textAlign`, a font
 * family preset stored in `style`, custom colors and gradient attributes, the
 * `align` attribute, the squared block style, and the hex `color` and
 * `textColor` of the first versions.
 *
 * Attribute-only: the markup of all those versions (classes and inline
 * styles on the wrapper and on the link) is regenerated by the parser from
 * the migrated attributes.
 */
const legacyAttributes = {
	attributes: {
		...blockAttributes,
		align: {
			type: 'string',
		},
		borderRadius: {
			type: 'number',
		},
		color: {
			type: 'string',
		},
		customBackgroundColor: {
			type: 'string',
		},
		customGradient: {
			type: 'string',
		},
		customTextColor: {
			type: 'string',
		},
		textAlign: {
			type: 'string',
		},
		width: {
			type: 'number',
		},
	},
	supports: blockSupports,
	isEligible( {
		align,
		borderRadius,
		className,
		color,
		customBackgroundColor,
		customGradient,
		customTextColor,
		style,
		textAlign,
		textColor,
		width,
	}: ButtonAttributes ) {
		return (
			typeof width === 'number' ||
			typeof borderRadius === 'number' ||
			typeof style?.border?.radius === 'number' ||
			!! style?.typography?.fontFamily ||
			!! textAlign ||
			!! customTextColor ||
			!! customBackgroundColor ||
			!! customGradient ||
			( !! align && LEGACY_ALIGNMENTS.includes( align ) ) ||
			!! className?.includes( 'is-style-squared' ) ||
			color !== undefined ||
			isHex( textColor )
		);
	},
	migrate: compose(
		migrateWidth,
		migrateTextAlign,
		migrateFontFamily,
		migrateBorderRadius,
		migrateSquaredStyle,
		migrateCustomColorsAndGradients,
		migrateOldColors,
		migrateAlign
	) as ( attributes: ButtonAttributes ) => ButtonAttributes,
};

export default [ legacyAttributes ];
