import metadata from './block.json';

const { attributes: blockAttributes, supports: blockSupports } = metadata;

type TableAttributes = Record< string, unknown > & {
	hasFixedLayout?: boolean;
	backgroundColor?: string;
	style?: Record< string, unknown >;
};

// As the previous arbitrary colors won't match theme color palettes, the hex
// value will be mapped to the style.color.background attribute as if it was
// a custom color selection.
const oldColors: Record< string, string > = {
	'subtle-light-gray': '#f3f4f5',
	'subtle-pale-green': '#e9fbe5',
	'subtle-pale-blue': '#e7f5fe',
	'subtle-pale-pink': '#fcf0ef',
};

/**
 * Deprecation for the `hasFixedLayout` attribute defaulting to `false`.
 *
 * Attribute-only: the markup of those versions (cell attributes, the caption
 * class) is regenerated by the parser. A table saved before the default
 * changed has neither the attribute in its delimiter nor the class in its
 * markup, while a current table without fixed layout stores the attribute.
 */
const fixedLayoutOffByDefault = {
	attributes: {
		...blockAttributes,
		hasFixedLayout: {
			type: 'boolean',
			default: false,
		},
	},
	supports: blockSupports,
	isEligible(
		{ hasFixedLayout }: TableAttributes,
		innerBlocks: unknown,
		{ block }: { block: { originalContent?: string } }
	) {
		return (
			hasFixedLayout === undefined &&
			! /\bhas-fixed-layout\b/.test( block.originalContent ?? '' )
		);
	},
};

/**
 * Deprecation migrating the table block to use the colors block support.
 *
 * Attribute-only: the color classes of that version are regenerated by the
 * parser from the migrated `style` attribute.
 */
const legacyColors = {
	attributes: {
		...blockAttributes,
		hasFixedLayout: {
			type: 'boolean',
			default: false,
		},
	},
	supports: blockSupports,
	isEligible( attributes: TableAttributes ) {
		return (
			!! attributes.backgroundColor &&
			attributes.backgroundColor in oldColors &&
			! attributes.style
		);
	},
	// This version is the first to introduce the style attribute to the
	// table block. As a result, we'll explicitly override that.
	migrate( attributes: TableAttributes ) {
		return {
			...attributes,
			backgroundColor: undefined,
			style: {
				color: {
					background: oldColors[ attributes.backgroundColor! ],
				},
			},
		};
	},
};

export default [ fixedLayoutOffByDefault, legacyColors ];
