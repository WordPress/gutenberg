import metadata from './block.json';
import migrateTextAlignAttributeToBlockSupport from '../utils/migrate-text-align';

const { attributes: blockAttributes, supports: blockSupports } = metadata;

type HeadingAttributes = Record< string, unknown > & {
	align?: string;
	textAlign?: string;
	customTextColor?: string;
	className?: string;
};

const migrateCustomColors = ( attributes: HeadingAttributes ) => {
	if ( ! attributes.customTextColor ) {
		return attributes;
	}
	const style = {
		color: {
			text: attributes.customTextColor,
		},
	};

	const { customTextColor, ...restAttributes } = attributes;

	return {
		...restAttributes,
		style,
	};
};

const TEXT_ALIGN_OPTIONS = [ 'left', 'right', 'center' ];

const migrateTextAlign = ( attributes: HeadingAttributes ) => {
	const { align, ...rest } = attributes;
	return align && TEXT_ALIGN_OPTIONS.includes( align )
		? { ...rest, textAlign: align }
		: attributes;
};

/**
 * Deprecation for the text alignment and custom text color attributes, which
 * moved to the typography and color block supports: `align` (later
 * `textAlign`) became `style.typography.textAlign` and `customTextColor`
 * became `style.color.text`.
 *
 * Attribute-only: the markup of those versions (an inline `text-align` style
 * or a `has-text-align-*` class, color classes and styles, the block class)
 * is regenerated by the parser from the migrated attributes.
 */
const legacyAlignAndColors = {
	attributes: {
		...blockAttributes,
		align: {
			type: 'string',
		},
		textAlign: {
			type: 'string',
		},
		customTextColor: {
			type: 'string',
		},
	},
	supports: blockSupports,
	isEligible( {
		align,
		textAlign,
		customTextColor,
		className,
	}: HeadingAttributes ) {
		return (
			( !! align && TEXT_ALIGN_OPTIONS.includes( align ) ) ||
			!! textAlign ||
			!! customTextColor ||
			!! className?.match( /\bhas-text-align-(left|center|right)\b/ )
		);
	},
	migrate: ( attributes: HeadingAttributes ) =>
		migrateTextAlignAttributeToBlockSupport(
			migrateCustomColors( migrateTextAlign( attributes ) )
		),
};

export default [ legacyAlignAndColors ];
