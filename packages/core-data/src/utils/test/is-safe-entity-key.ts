import { describe, expect, test } from 'vitest';
import isSafeEntityKey from '../is-safe-entity-key';

describe( 'isSafeEntityKey', () => {
	test.each( [
		[ true, '12345' ],
		[ true, 42 ],
		[ true, '' ],
		[ true, null ],
		[ true, undefined ],
		[ true, 'twentytwentyfour//header' ],
		[ true, 'twentytwentyfour//my-header-part' ],
		[ true, 'my-post-slug' ],
		[ true, 'akismet/akismet' ],
		[ true, 'core/paragraph' ],
		[ true, 'twentytwentyfive//%e4%b8%ad%e6%96%87' ],
		[ true, 'header.part' ],
		[ true, '...' ],
		[ true, 'header%' ],
		[ true, 'header%zz' ],
		[ false, 'twentytwentyfour//header?_x=Y' ],
		[ false, 'header?_x=Y&a=b' ],
		[ false, 'header?_x=Y?a=b' ],
		[ false, 'header#fragment' ],
		[ false, 'header&_x=Y' ],
		[ false, 'twentytwentyfive//header&x_y=/a/b/c' ],
		[ false, 'header\\..\\id' ],
		[ false, 'header\x00' ],
		[ false, 'header\x1f' ],
		[ false, 'header\x7f' ],
		[ false, 'header\t' ],
		[ false, 'header\n' ],
		[ false, '../users' ],
		[ false, 'theme/../../users' ],
		[ false, 'theme/./users' ],
		[ false, '.' ],
		[ false, '..' ],
		[ false, 'theme/%2e./users' ],
		[ false, 'theme/.%2e/users' ],
		[ false, 'theme/%2e%2e/users' ],
		[ false, 'theme/%2E%2E/users' ],
		[ false, '%2e%2e' ],
		[ false, 'header%3f_x=Y' ],
		[ false, 'header%3F_x=Y' ],
		[ false, 'header%23fragment' ],
		[ false, 'header%26_x=Y' ],
		[ false, 'header%5c..%5cid' ],
		[ false, 'header%00' ],
		[ false, 'header%2fautosaves' ],
		[ false, 'header%2F..%2F..%2Fusers' ],
		[ false, {} ],
		[ false, [] ],
		[ false, true ],
	] )( `should return %s for input %j`, ( expected, input ) => {
		expect( isSafeEntityKey( input ) ).toBe( expected );
	} );
} );
