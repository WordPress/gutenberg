/**
 * Weight names a font may use for its style, mapped to the numeric CSS weight
 * they stand for, as listed in the CSS Fonts 4 common weight name mapping.
 *
 * Names that carry no weight of their own ("Regular", "Italic") are absent on
 * purpose: for those the font's own `OS/2.usWeightClass` is the better source.
 */
const WEIGHT_NAMES: Record< string, number > = {
	thin: 100,
	hairline: 100,
	extralight: 200,
	ultralight: 200,
	light: 300,
	medium: 500,
	semibold: 600,
	demibold: 600,
	bold: 700,
	extrabold: 800,
	ultrabold: 800,
	black: 900,
	heavy: 900,
};

/**
 * Reads the numeric font weight out of a font's style name.
 *
 * Fonts cannot always be trusted to report their weight numerically. Static
 * instances generated by Google Fonts, for example, give both the Thin and the
 * ExtraLight face an `OS/2.usWeightClass` of 250, a legacy Windows constraint
 * on weights below 250. Both faces then look identical to WordPress, which
 * identifies a font face by family, style and weight, and installing the two
 * together fails as a duplicate. Their style names still tell the two apart.
 *
 * @param styleName The font's style name, such as `Thin` or `Bold Italic`.
 * @return The numeric weight, or `undefined` when the name names no weight.
 */
export default function getWeightFromStyleName(
	styleName?: string
): number | undefined {
	if ( ! styleName ) {
		return undefined;
	}

	// Drop the slant, so that "Thin Italic" is read as "Thin".
	const weightName = styleName
		.toLowerCase()
		.replace( /italic|oblique/g, '' )
		.replace( /\s+/g, '' );

	return WEIGHT_NAMES[ weightName ];
}
