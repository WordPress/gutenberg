/**
 * External dependencies
 */
const path = require( 'path' );
const { readFile, writeFile, mkdir } = require( 'fs' ).promises;

const MANIFEST_JSON_PATH = path.join( __dirname, '..', 'src', 'manifest.json' );
const LIBRARY_DIR = path.join( __dirname, '..', 'src', 'library' );
const OUTPUT_DIR = path.join( __dirname, '..', 'build-php' );
const ICONS_DATA_PATH = path.join( OUTPUT_DIR, 'icons-data.php' );

/**
 * Escapes a string for safe inclusion in a PHP single-quoted string.
 *
 * @param {string} str
 * @return {string} Escaped string.
 */
function escapePHPString( str ) {
	return str.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" );
}

/**
 * Extracts the inner content and viewBox from an SVG file's content.
 *
 * @param {string} svgContent Raw SVG file content.
 * @return {{ viewBox: string, content: string }} Parsed SVG data.
 */
function parseSVG( svgContent ) {
	const viewBoxMatch = svgContent.match( /viewBox="([^"]*)"/ );
	const viewBox = viewBoxMatch ? viewBoxMatch[ 1 ] : '0 0 24 24';

	// Extract inner content between <svg ...> and </svg>.
	const innerMatch = svgContent.match( /<svg[^>]*>([\s\S]*)<\/svg>/ );
	const innerContent = innerMatch ? innerMatch[ 1 ] : '';

	// Collapse whitespace: trim lines, remove blank lines, collapse to single line.
	const content = innerContent
		.split( '\n' )
		.map( ( line ) => line.trim() )
		.filter( ( line ) => line.length > 0 )
		.join( '' );

	return { viewBox, content };
}

/**
 * Generates the PHP icons data file from the JSON manifest and SVG sources.
 */
async function generateIconsDataPHP() {
	const manifestJson = await readFile( MANIFEST_JSON_PATH, 'utf8' );
	const manifest = JSON.parse( manifestJson );

	const maxKeyLength = Math.max(
		...manifest.map( ( item ) => item.slug.length )
	);

	const entries = [];
	for ( const item of manifest ) {
		const svgPath = path.join(
			LIBRARY_DIR,
			path.basename( item.filePath )
		);
		const svgContent = await readFile( svgPath, 'utf8' );
		const { viewBox, content } = parseSVG( svgContent );

		const padding = ' '.repeat( maxKeyLength - item.slug.length );
		const key = `\t'${ escapePHPString( item.slug ) }'${ padding }`;

		entries.push(
			`${ key } => array(
		'viewBox'  => '${ escapePHPString( viewBox ) }',
		'content'  => '${ escapePHPString( content ) }',
	),`
		);
	}

	const phpContent = `<?php
/**
 * Auto-generated icon data. Do not edit directly.
 *
 * Generated by packages/icons/lib/generate-icons-php.cjs
 *
 * @package gutenberg
 */

if ( ! defined( 'ABSPATH' ) ) {
	die( 'Silence is golden.' );
}

return array(
${ entries.join( '\n' ) }
);
`;

	await mkdir( OUTPUT_DIR, { recursive: true } );
	await writeFile( ICONS_DATA_PATH, phpContent, 'utf8' );
}

if ( module === require.main ) {
	generateIconsDataPHP();
}

module.exports = { generateIconsDataPHP };
