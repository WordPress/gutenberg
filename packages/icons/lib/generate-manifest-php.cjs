const path = require( 'path' );
const { readFile, writeFile } = require( 'fs' ).promises;

const MANIFEST_JSON_PATH = path.join( __dirname, '..', 'src', 'manifest.json' );
const MANIFEST_PHP_PATH = path.join( __dirname, '..', 'src', 'manifest.php' );
const INLINED_ICONS_PHP_PATH = path.join(
	__dirname,
	'..',
	'src',
	'inlined-icons.php'
);
const ICONS_DIR = path.join( __dirname, '..', 'src' );

/**
 * The collection whose icons get their SVG markup inlined in a PHP file.
 *
 * The icons of the core-admin collection are rendered on every page of the
 * WordPress admin interface, in the admin menu and the admin bar. Inlining
 * their markup means that WordPress doesn't need to read and sanitize their
 * files on each of those requests.
 */
const INLINED_COLLECTION = 'core-admin';

const PHP_HEADER = `<?php
// This file is automatically generated. Do not edit directly.
if ( ! defined( 'ABSPATH' ) ) {
	die( 'Silence is golden.' );
}

`;

/**
 * Escapes single quotes in PHP strings.
 *
 * @param {string} str String to escape.
 * @return {string} Escaped string.
 */
function escapePHPString( str ) {
	return str.replace( /'/g, "\\'" );
}

/**
 * Formats a PHP array key with proper indentation and alignment.
 *
 * @param {string} key          Array key.
 * @param {number} maxKeyLength Maximum key length for alignment.
 * @return {string} Formatted key.
 */
function formatPHPKey( key, maxKeyLength ) {
	const padding = ' '.repeat( maxKeyLength - key.length );
	return `\t'${ escapePHPString( key ) }'${ padding }`;
}

/**
 * Generates PHP array from JSON manifest.
 *
 * @param {Array} manifest JSON manifest array.
 * @return {string} PHP code.
 */
function generatePHPArray( manifest ) {
	// Find the maximum key length for alignment
	const maxKeyLength = Math.max(
		...manifest.map( ( item ) => item.slug.length )
	);

	const phpEntries = manifest.map( ( item ) => {
		const key = formatPHPKey( item.slug, maxKeyLength );
		const label = escapePHPString( item.label );
		const filePath = escapePHPString( item.filePath );
		const collections = item.collections
			.map( ( collection ) => `'${ escapePHPString( collection ) }'` )
			.join( ', ' );

		// Keywords are optional, and are localized like labels since they are
		// matched against user-entered search terms.
		const keywords = item.keywords?.length
			? `\n\t\t'keywords'    => array( ${ item.keywords
					.map(
						( keyword ) =>
							`_x( '${ escapePHPString(
								keyword
							) }', 'icon keyword', 'gutenberg' )`
					)
					.join( ', ' ) } ),`
			: '';

		return `${ key } => array(
		'label'       => _x( '${ label }', 'icon label', 'gutenberg' ),
		'filePath'    => '${ filePath }',
		'collections' => array( ${ collections } ),${ keywords }
	),`;
	} );

	return `return array(
${ phpEntries.join( '\n' ) }
);`;
}

/**
 * Prepares the SVG markup of an icon to be inlined in a PHP file. The
 * whitespace between tags is removed so that each icon fits on a single line.
 *
 * @param {string} svg SVG markup, as read from the icon file.
 * @return {string} SVG markup on a single line.
 */
function inlineSvg( svg ) {
	return svg.trim().replace( />\s+</g, '><' );
}

/**
 * Generates a PHP array which maps namespaced icon names to their SVG markup.
 *
 * @param {Array<{name: string, svg: string}>} icons Icons to inline.
 * @return {string} PHP code.
 */
function generateInlinedIconsPHPArray( icons ) {
	const maxKeyLength = Math.max(
		...icons.map( ( icon ) => icon.name.length )
	);

	const phpEntries = icons.map( ( icon ) => {
		const key = formatPHPKey( icon.name, maxKeyLength );
		const svg = escapePHPString(
			inlineSvg( icon.svg ).replace( /\\/g, '\\\\' )
		);

		return `${ key } => '${ svg }',`;
	} );

	return `return array(
${ phpEntries.join( '\n' ) }
);`;
}

/**
 * Generates manifest.php from manifest.json.
 * Only includes icons which belong to at least one collection, since those are
 * the icons shipped to WordPress Core.
 *
 * @param {Array} manifest JSON manifest array.
 */
async function generateManifestPHP( manifest ) {
	const includedIcons = manifest.filter(
		( item ) => item.collections?.length > 0
	);
	const phpArray = generatePHPArray( includedIcons );
	const phpContent = PHP_HEADER + phpArray + '\n';
	await writeFile( MANIFEST_PHP_PATH, phpContent, 'utf8' );
}

/**
 * Generates inlined-icons.php, which holds the SVG markup of the icons which
 * belong to the inlined collection, keyed by their namespaced name.
 *
 * @param {Array} manifest JSON manifest array.
 */
async function generateInlinedIconsPHP( manifest ) {
	const icons = await Promise.all(
		manifest
			.filter( ( item ) =>
				item.collections?.includes( INLINED_COLLECTION )
			)
			.map( async ( item ) => ( {
				name: `${ INLINED_COLLECTION }/${ item.slug }`,
				svg: await readFile(
					path.join( ICONS_DIR, item.filePath ),
					'utf8'
				),
			} ) )
	);
	const phpArray = generateInlinedIconsPHPArray( icons );
	const phpContent = PHP_HEADER + phpArray + '\n';
	await writeFile( INLINED_ICONS_PHP_PATH, phpContent, 'utf8' );
}

/**
 * Generates the PHP files derived from manifest.json.
 */
async function generate() {
	const manifestJson = await readFile( MANIFEST_JSON_PATH, 'utf8' );
	const manifest = JSON.parse( manifestJson );

	await generateManifestPHP( manifest );
	await generateInlinedIconsPHP( manifest );
}

if ( module === require.main ) {
	generate();
}

module.exports = { generateInlinedIconsPHPArray, inlineSvg };
