/**
 * Shared helpers for the overlapping-suggestion specs: the reviewer
 * accounts, the shared overlap fixtures (read from the data the oracle
 * generates for them), seeding a fixture through REST, and the compact
 * rendering every comparison uses.
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export type Decision = 'accept' | 'reject';

export interface OverlapOrderStep {
	key: string;
	decision: Decision;
	/** What the editor shows after the step. */
	displayed: string;
	/** Suggestions outdated so far. */
	outdated: string[];
}

export interface OverlapFixture {
	name: string;
	phase: 'current' | 'A' | 'B';
	users: Record< string, string >;
	/** Paragraph HTML with `{{id:KEY}}` and `{{author:KEY}}` placeholders. */
	html: string;
	suggestions: Array< {
		key: string;
		author: string;
		operation: Record< string, unknown >;
	} >;
	views: { displayed: string; acceptedHTML: string; rejectedHTML: string };
	orders: {
		exhaustive: boolean;
		list: Array< {
			label: string;
			steps: OverlapOrderStep[];
			published: string;
		} >;
	};
}

/**
 * Reviewer accounts, by username. Fixtures name their authors by username.
 */
export const OVERLAP_USERS: Record<
	string,
	{ username: string; email: string; password: string; name: string }
> = Object.fromEntries(
	[ 'Anne', 'Bob', 'Carl', 'Dana' ].map( ( name ) => {
		const username = `overlap-${ name.toLowerCase() }`;
		return [
			username,
			{
				username,
				email: `${ username.replace( '-', '.' ) }@example.com`,
				password: `${ username.replace( '-', '' ) }password`,
				name,
			},
		];
	} )
);

/**
 * Create the reviewer accounts as editors.
 *
 * @param requestUtils Request utils.
 * @return User ids by username.
 */
export async function createOverlapUsers( requestUtils: any ) {
	const ids: Record< string, number > = {};
	for ( const user of Object.values( OVERLAP_USERS ) ) {
		const created = await requestUtils.createUser( {
			username: user.username,
			email: user.email,
			password: user.password,
			roles: [ 'editor' ],
		} );
		await requestUtils.rest( {
			method: 'PUT',
			path: `/wp/v2/users/${ created.id }`,
			data: { name: user.name },
		} );
		ids[ user.username ] = created.id;
	}
	return ids;
}

const GENERATED = join(
	__dirname,
	'../../../../../packages/editor/src/components/inline-suggestions/test/fixtures/overlaps/generated'
);

/**
 * Every shared overlap fixture, as generated by the oracle.
 *
 * @return Fixtures.
 */
export function loadOverlapFixtures(): OverlapFixture[] {
	return readdirSync( GENERATED )
		.filter( ( file ) => file.endsWith( '.json' ) )
		.sort()
		.map( ( file ) =>
			JSON.parse( readFileSync( join( GENERATED, file ), 'utf8' ) )
		);
}

/**
 * Phases of the overlap plan that have landed. Add a phase when it lands;
 * set `OVERLAP_PHASES=A` to run a phase's tests before then.
 */
export const LANDED_PHASES = [ 'current', 'A', 'B' ];

/**
 * Whether a phase has landed, or is forced on through `OVERLAP_PHASES`.
 *
 * @param phase Phase.
 * @return Whether its tests run.
 */
export function isPhaseLanded( phase: string ) {
	return (
		LANDED_PHASES.includes( phase ) ||
		( process.env.OVERLAP_PHASES ?? '' )
			.split( ',' )
			.map( ( p ) => p.trim() )
			.includes( phase )
	);
}

/**
 * Seed a fixture: a draft post whose paragraph holds the fixture's markers,
 * with a pending note per suggestion by its author.
 *
 * @param requestUtils Request utils.
 * @param fixture      Fixture.
 * @param userIds      User ids by username.
 * @return Post id and note ids by suggestion key.
 */
export async function seedOverlapFixture(
	requestUtils: any,
	fixture: OverlapFixture,
	userIds: Record< string, number >
) {
	const post = await requestUtils.createPost( {
		title: `Overlap: ${ fixture.name }`,
		content: '<!-- wp:paragraph --><p>x</p><!-- /wp:paragraph -->',
		status: 'draft',
	} );
	const ids: Record< string, number > = {};
	const authors: Record< string, number > = {};
	for ( const { key, author, operation } of fixture.suggestions ) {
		authors[ key ] = userIds[ fixture.users[ author ] ];
		const note = await requestUtils.rest( {
			method: 'POST',
			path: '/wp/v2/comments',
			data: {
				post: post.id,
				content: '',
				type: 'note',
				status: 'hold',
				parent: 0,
				author: authors[ key ],
				meta: {
					_wp_suggestion: JSON.stringify( {
						schemaVersion: 2,
						blockName: 'core/paragraph',
						baseRevision: null,
						operations: [ operation ],
					} ),
				},
			},
		} );
		ids[ key ] = note.id;
	}
	const paragraph = fixture.html.replace(
		/\{\{(id|author):(\w+)\}\}/g,
		( _match, what, key ) =>
			String( what === 'id' ? ids[ key ] : authors[ key ] )
	);
	const metadata = JSON.stringify( { noteId: Object.values( ids ) } );
	await requestUtils.rest( {
		method: 'PUT',
		path: `/wp/v2/posts/${ post.id }`,
		data: {
			content: `<!-- wp:paragraph {"metadata":${ metadata }} -->\n<p>${ paragraph }</p>\n<!-- /wp:paragraph -->`,
		},
	} );
	return { postId: post.id as number, ids };
}

const TAGS: Record< string, string > = {
	strong: 'b',
	b: 'b',
	em: 'i',
	i: 'i',
};
const ORDER = [ 'b', 'i' ];

/**
 * The compact rendering the oracle uses, read from HTML: text, with bold in
 * `<b>` and italic in `<i>`. Markers and other tags only contribute their
 * text.
 *
 * @param html HTML.
 * @return Rendering.
 */
export function renderOverlapHTML( html: string ) {
	const chars: Array< { ch: string; formats: string[] } > = [];
	const open: string[] = [];
	for ( const token of html.match( /<[^>]+>|[^<]+/g ) ?? [] ) {
		const tag = token.match( /^<(\/?)([a-z]+)/i );
		if ( tag ) {
			const short = TAGS[ tag[ 2 ].toLowerCase() ];
			if ( short && tag[ 1 ] ) {
				open.splice( open.lastIndexOf( short ), 1 );
			} else if ( short ) {
				open.push( short );
			}
			continue;
		}
		for ( const ch of token
			.replace( /&nbsp;/g, ' ' )
			.replace( /&amp;/g, '&' ) ) {
			chars.push( {
				ch,
				formats: [ ...new Set( open ) ].sort(
					( a, b ) => ORDER.indexOf( a ) - ORDER.indexOf( b )
				),
			} );
		}
	}
	let out = '';
	let current: string[] = [];
	for ( const { ch, formats } of chars ) {
		let common = 0;
		while (
			common < current.length &&
			common < formats.length &&
			current[ common ] === formats[ common ]
		) {
			common++;
		}
		for ( let i = current.length - 1; i >= common; i-- ) {
			out += `</${ current[ i ] }>`;
		}
		for ( let i = common; i < formats.length; i++ ) {
			out += `<${ formats[ i ] }>`;
		}
		current = formats;
		out += ch;
	}
	for ( let i = current.length - 1; i >= 0; i-- ) {
		out += `</${ current[ i ] }>`;
	}
	return out;
}

/**
 * The first block's `content` attribute.
 *
 * @param page Playwright page.
 * @return HTML.
 */
export async function firstBlockHTML( page: any ): Promise< string > {
	return page.evaluate( () => {
		const [ block ] = window.wp.data
			.select( 'core/block-editor' )
			.getBlocks();
		return String( block.attributes.content );
	} );
}

/**
 * Open the notes sidebar if it is closed.
 *
 * @param page Playwright page.
 * @return The sidebar region.
 */
export async function openNotesSidebar( page: any ) {
	const toggle = page
		.getByRole( 'region', { name: 'Editor top bar' } )
		.getByRole( 'button', { name: 'All notes', exact: true } );
	if ( ( await toggle.getAttribute( 'aria-expanded' ) ) === 'false' ) {
		await toggle.click();
	}
	return page.getByRole( 'region', { name: 'Editor settings' } );
}

/**
 * Accept or reject a suggestion from its thread in the sidebar, and wait for
 * the decision to save.
 *
 * @param page     Playwright page.
 * @param sidebar  The sidebar region.
 * @param noteId   Suggestion note id.
 * @param decision Decision.
 */
export async function decideSuggestion(
	page: any,
	sidebar: any,
	noteId: number,
	decision: Decision
) {
	const decided = page.waitForResponse(
		( response: any ) =>
			response.url().includes( `/wp/v2/comments/${ noteId }` ) &&
			response.ok()
	);
	await sidebar
		.locator( `#note-thread-${ noteId }` )
		.getByRole( 'button', {
			name:
				decision === 'accept'
					? 'Accept suggestion'
					: 'Reject suggestion',
		} )
		.click();
	await decided;
}
