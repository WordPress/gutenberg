import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
	createBlock,
	getBlockTypes,
	parse,
	serialize,
	unregisterBlockType,
} from '@wordpress/blocks';
import type { Block } from '@wordpress/blocks';
import { registerCoreBlocks } from '../../packages/block-library/src';
import { migrateToListV2 } from '../../packages/block-library/src/list/utils';

describe( 'legacy List migration', () => {
	beforeAll( () => registerCoreBlocks() );
	afterAll( () => {
		getBlockTypes().forEach( ( { name } ) => unregisterBlockType( name ) );
	} );

	it.each( [
		'First[efn_note]This is a <a href="https://www.example.com">note</a>.[/efn_note]',
		'First[custom_note]<strong>Note</strong>[/custom_note]',
		'First[caption]<a href="https://example.com">caption</a>[/caption]',
		'First[[custom_note]<strong>Note</strong>[/custom_note]]',
		'First[custom_note option="value"]Plain text[/custom_note]',
		'First <a href="https://example.com/?filter[year]=2026">link</a>',
		'First [ unmatched bracket',
	] )( 'preserves item content and following items: %s', ( content ) => {
		const [ attributes, innerBlocks ] = migrateToListV2( {
			values: `<li>${ content }</li><li>Second</li>`,
		} );

		expect( innerBlocks ).toHaveLength( 2 );
		expect( String( innerBlocks[ 0 ].attributes.content ) ).toBe( content );
		expect( String( innerBlocks[ 1 ].attributes.content ) ).toBe(
			'Second'
		);
		expect( attributes.ordered ).toBe( false );
	} );

	it( 'retains already encoded shortcode brackets as text', () => {
		const [ , innerBlocks ] = migrateToListV2( {
			values: '<li>&#91;efn_note]A <a href="https://example.com">note</a>.&#91;/efn_note]</li><li>Second</li>',
		} );

		expect( innerBlocks ).toHaveLength( 2 );
		expect( String( innerBlocks[ 0 ].attributes.content ) ).toBe(
			'[efn_note]A <a href="https://example.com">note</a>.[/efn_note]'
		);
	} );

	it( 'preserves ordered list settings and normalizes multiple nested lists', () => {
		const [ attributes, innerBlocks ] = migrateToListV2( {
			ordered: true,
			start: 4,
			reversed: true,
			type: 'A',
			className: 'custom-list',
			anchor: 'legacy-list',
			style: { color: { text: '#123456' } },
			values: '<li>First<ul><li>Nested one</li></ul><ul><li>Nested two</li></ul></li><li>Second</li>',
		} );

		expect( attributes ).toMatchObject( {
			ordered: true,
			start: 4,
			reversed: true,
			type: 'upper-alpha',
			className: 'custom-list',
			anchor: 'legacy-list',
			style: { color: { text: '#123456' } },
		} );
		expect( innerBlocks ).toHaveLength( 2 );
		expect( innerBlocks[ 0 ].innerBlocks ).toHaveLength( 1 );
		expect(
			innerBlocks[ 0 ].innerBlocks[ 0 ].innerBlocks.map(
				( block: Block ) => String( block.attributes.content )
			)
		).toEqual( [ 'Nested one', 'Nested two' ] );
	} );

	it( 'preserves shortcode links and all items through parsing and reserialization', () => {
		const content =
			'First[efn_note]This is a <a href="https://www.example.com">note</a>.[/efn_note]';
		const [ migrated ] = parse(
			`<!-- wp:list -->\n<ul><li>${ content }</li><li>Second</li></ul>\n<!-- /wp:list -->`
		);
		expect( console ).toHaveLoggedWith( 'Updated Block: %s', 'core/list' );
		expect( console ).toHaveInformedWith(
			'Block successfully updated for `%s` (%o).\n\nNew content generated by `save` function:\n\n%s\n\nContent retrieved from post body:\n\n%s',
			'core/list',
			expect.objectContaining( { name: 'core/list' } ),
			expect.any( String ),
			`<ul><li>${ content }</li><li>Second</li></ul>`
		);

		expect( migrated.isValid ).toBe( true );
		expect( migrated.innerBlocks ).toHaveLength( 2 );
		expect( String( migrated.innerBlocks[ 0 ].attributes.content ) ).toBe(
			content
		);
		const saved = serialize( migrated );
		const [ reloaded ] = parse( saved );
		expect( serialize( reloaded ) ).toBe( saved );
		expect( String( reloaded.innerBlocks[ 1 ].attributes.content ) ).toBe(
			'Second'
		);
	} );

	it( 'keeps shortcode text in a nested list', () => {
		const content =
			'[efn_note]A <a href="https://example.com">nested note</a>.[/efn_note]';
		const [ attributes, innerBlocks ] = migrateToListV2( {
			values: `<li>First<ul><li>${ content }</li><li>Nested second</li></ul></li><li>Second</li>`,
		} );
		const saved = serialize(
			createBlock( 'core/list', attributes, innerBlocks )
		);

		expect( saved ).toContain( content );
		expect( saved ).toContain( '<li>Nested second</li>' );
		expect( saved ).toContain( '<li>Second</li>' );
	} );
} );
